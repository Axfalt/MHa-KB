//! Topic dossiers: Claude researches each topic of `knowledge/topics.yaml` with the knowledge-base
//! tools and writes a cited Markdown page to `knowledge/topics/<id>.md`. The pages are committed, so
//! people can review and correct them; `mhkb ingest topics` indexes them.

use std::path::Path;

use anyhow::{Context, Result};
use futures::stream::{self, StreamExt};
use kb_core::answer::{self, AnswerConfig};
use kb_core::claude::Claude;
use kb_core::embed::Embedder;
use kb_core::store::NewDoc;
use serde::Deserialize;
use serde_json::json;
use sqlx::PgPool;
use tracing::{info, warn};

#[derive(Deserialize)]
pub struct Topic {
    pub id: String,
    pub title: String,
    pub scope: String,
}

pub fn load_topics(knowledge: &Path) -> Result<Vec<Topic>> {
    let path = knowledge.join("topics.yaml");
    serde_yaml::from_str(&std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?)
        .with_context(|| format!("parsing {}", path.display()))
}

const HEADER_PREFIX: &str = "<!-- Generated by `mhkb dossier`";

pub struct Options {
    pub only: Vec<String>,
    pub force: bool,
    pub effort: String,
    pub parallel: usize,
}

pub async fn run(pool: &PgPool, embedder: &Embedder, claude: &Claude, cfg: &AnswerConfig, knowledge: &Path, opts: &Options) -> Result<()> {
    let dir = knowledge.join("topics");
    std::fs::create_dir_all(&dir)?;
    let topics: Vec<Topic> = load_topics(knowledge)?
        .into_iter()
        .filter(|t| opts.only.is_empty() || opts.only.contains(&t.id))
        .filter(|t| opts.force || !dir.join(format!("{}.md", t.id)).exists())
        .collect();
    if topics.is_empty() {
        info!("all dossiers exist (use --force to regenerate)");
        return Ok(());
    }
    let git_sha: Option<String> = sqlx::query_scalar("SELECT git_sha FROM source_files WHERE git_sha IS NOT NULL LIMIT 1").fetch_optional(pool).await?.flatten();
    info!(topics = topics.len(), parallel = opts.parallel, "writing dossiers");

    let results: Vec<(String, Result<f64>)> = stream::iter(topics.iter())
        .map(|topic| async {
            let result = async {
                let a = answer::research(pool, embedder, claude, cfg, &opts.effort, &topic.title, &topic.scope).await?;
                let mut page = format!(
                    "{HEADER_PREFIX} with {} from MyHordes {}. Review welcome: fix mistakes directly; `mhkb dossier --force --only {}` regenerates it. -->\n\n{}\n",
                    a.model,
                    git_sha.as_deref().map(|s| &s[..s.len().min(10)]).unwrap_or("?"),
                    topic.id,
                    a.text.trim()
                );
                page.push_str("\n## Sources\n\n");
                for (i, s) in a.sources.iter().enumerate() {
                    page.push_str(&format!("{}. {} — `{}`\n", i + 1, s.title, s.key));
                }
                std::fs::write(dir.join(format!("{}.md", topic.id)), page)?;
                if !a.unknown_citations.is_empty() {
                    warn!(topic = %topic.id, unknown = ?a.unknown_citations, "dropped citations to unseen documents");
                }
                info!(topic = %topic.id, sources = a.sources.len(), tool_calls = a.tool_calls.len(), outcome = %a.outcome, cost = format!("{:.3}", a.cost_usd), "dossier written");
                Ok(a.cost_usd)
            }
            .await;
            (topic.id.clone(), result)
        })
        .buffer_unordered(opts.parallel.max(1))
        .collect()
        .await;

    let mut total = 0.0;
    for (id, r) in results {
        match r {
            Ok(cost) => total += cost,
            Err(e) => warn!(topic = %id, error = %e, "dossier failed"),
        }
    }
    info!(cost_usd = format!("{total:.2}"), "dossiers done");
    Ok(())
}

/// `topic:` documents from `knowledge/topics/*.md`
pub fn documents(knowledge: &Path) -> Result<Vec<NewDoc>> {
    let dir = knowledge.join("topics");
    if !dir.exists() {
        return Ok(vec![]);
    }
    let mut files: Vec<_> = std::fs::read_dir(&dir)?.filter_map(|e| e.ok()).map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "md")).collect();
    files.sort();
    let mut docs = Vec::new();
    for path in files {
        let id = path.file_stem().unwrap_or_default().to_string_lossy().to_string();
        let raw = std::fs::read_to_string(&path)?;
        // Drop the generation header; the numbered source list stays, so the bot can open the sources
        let body = raw.lines().filter(|l| !l.starts_with(HEADER_PREFIX)).collect::<Vec<_>>().join("\n");
        let title = body.lines().find_map(|l| l.strip_prefix("# ")).unwrap_or(&id).trim().to_string();
        let content = body.lines().filter(|l| !l.starts_with("# ")).collect::<Vec<_>>().join("\n").trim().to_string();
        docs.push(NewDoc {
            key: format!("topic:{id}"),
            kind: "topic".into(),
            audience: "both".into(),
            title: format!("Dossier: {title}"),
            path: Some(format!("knowledge/topics/{id}.md")),
            content,
            meta: json!({ "topic": id }),
            ..Default::default()
        });
    }
    Ok(docs)
}
